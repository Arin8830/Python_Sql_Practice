-- 3. Create SENSORS Table
CREATE TABLE SENSORS (
    SENSOR_ID VARCHAR(10) PRIMARY KEY,
    RTU_ID VARCHAR(10) NOT NULL,
    STATUS VARCHAR(10) NOT NULL,
    SENSOR_TYPE VARCHAR(20) NOT NULL,
    REQ_VAL DECIMAL(10,2) NOT NULL,
    CURR_VAL DECIMAL(10,2),
    FOREIGN KEY (RTU_ID) REFERENCES RTU(RTU_ID),
    CHECK (STATUS IN ('ENABLED', 'DISABLED')),
    CHECK (REQ_VAL >= 0),
    CHECK (CURR_VAL >= 0 OR CURR_VAL IS NULL)
);

